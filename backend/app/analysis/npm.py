"""npm lockfile loading: lockfileVersion 1, 2 and 3 -> one normalized ``packages`` map.

v2/v3 ship a flat ``packages`` map keyed by install path (``node_modules/a/node_modules/b``).
v1 only has a nested ``dependencies`` tree; it is flattened into the same shape so that a
single graph builder (``graph.build_dependency_graph``) serves every npm lockfile.
"""
from __future__ import annotations

from typing import Any

from app.errors import Diagnostic, LockfileError

SUPPORTED_NPM_VERSIONS = (1, 2, 3)


def _split_alias(version: Any) -> tuple[str | None, Any]:
    """v1 stores npm aliases as ``"version": "npm:real-name@1.2.3"``."""
    if isinstance(version, str) and version.startswith("npm:"):
        spec = version[4:]
        at = spec.rfind("@")
        if at > 0:
            return spec[:at], spec[at + 1:]
    return None, version


def _flatten_v1(
    dependencies: dict[str, Any],
    prefix: str,
    out: dict[str, dict[str, Any]],
    problems: list[dict[str, str]],
) -> None:
    for name, entry in dependencies.items():
        path = f"{prefix}node_modules/{name}"
        if not isinstance(entry, dict):
            problems.append({"from": path, "dependency": "<invalid package entry>"})
            continue
        real_name, version = _split_alias(entry.get("version"))
        package: dict[str, Any] = {"version": version}
        if real_name:
            package["name"] = real_name
        for key in ("resolved", "integrity", "dev", "optional"):
            if key in entry:
                package[key] = entry[key]
        requires = entry.get("requires")
        if isinstance(requires, dict):
            package["dependencies"] = dict(requires)
        out[path] = package
        nested = entry.get("dependencies")
        if isinstance(nested, dict):
            _flatten_v1(nested, f"{path}/", out, problems)


def normalize_npm_lockfile(data: Any) -> tuple[dict[str, dict[str, Any]], int | None, list[Diagnostic], list[dict[str, str]]]:
    """Return (packages map, lockfileVersion, diagnostics, structural problems)."""
    if not isinstance(data, dict):
        raise LockfileError(
            "LOCKFILE_INVALID",
            "The lockfile does not contain a JSON object.",
            hint="Regenerate it with `npm install --package-lock-only`.",
        )
    diagnostics: list[Diagnostic] = []
    problems: list[dict[str, str]] = []
    version = data.get("lockfileVersion")
    if isinstance(version, bool) or not isinstance(version, (int, type(None))):
        version = None

    packages = data.get("packages")
    legacy = data.get("dependencies")

    if isinstance(packages, dict):
        if version is not None and version not in SUPPORTED_NPM_VERSIONS:
            diagnostics.append(Diagnostic(
                "LOCKFILE_VERSION_UNTESTED", "warning",
                f"npm lockfileVersion {version} is newer than the versions this analyzer was validated against (1-3); results may be incomplete.",
            ))
        return packages, version, diagnostics, problems

    if isinstance(legacy, dict):
        flat: dict[str, dict[str, Any]] = {"": {}}
        _flatten_v1(legacy, "", flat, problems)
        diagnostics.append(Diagnostic(
            "LOCKFILE_LEGACY_FORMAT", "info",
            "npm lockfile v1 (npm 5/6) was flattened to an install tree. It carries no peer-dependency or workspace data, so those relationships are not shown.",
            hint="Run `npm install --package-lock-only` with npm 7+ to upgrade the lockfile for fuller analysis.",
        ))
        return flat, version if version is not None else 1, diagnostics, problems

    if version is not None:
        # A valid lockfile for a project with no dependencies.
        diagnostics.append(Diagnostic("LOCKFILE_EMPTY", "info", "The npm lockfile lists no installed packages."))
        return {"": {}}, version, diagnostics, problems

    raise LockfileError(
        "LOCKFILE_INVALID",
        "This file is not a recognizable npm lockfile (no 'lockfileVersion', 'packages' or 'dependencies').",
        hint="Make sure the file is a package-lock.json / npm-shrinkwrap.json generated by npm.",
    )
